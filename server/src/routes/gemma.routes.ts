import { Router } from 'express';
import { authenticateToken, AuthenticatedRequest } from '../middleware/auth.js';
import { GemmaProviderService } from '../services/gemmaProvider.service.js';
import { CustomerService } from '../services/customer.service.js';
import { TransactionService } from '../services/transaction.service.js';
import { z } from 'zod';
import { validateBody } from '../middleware/validate.js';

export const gemmaRouter = Router();

gemmaRouter.use(authenticateToken);

// 1. Check Gemma provider status and active configuration
gemmaRouter.get('/status', (req: AuthenticatedRequest, res) => {
  const status = GemmaProviderService.getStatus();
  res.json(status);
});

// 2. Chat with Gemma assistant
const ChatSchema = z.object({
  prompt: z.string().trim().min(1, 'Prompt cannot be empty'),
  history: z
    .array(
      z.object({
        role: z.enum(['user', 'assistant', 'system']),
        content: z.string(),
      })
    )
    .optional()
    .default([]),
});

gemmaRouter.post('/chat', validateBody(ChatSchema), async (req: AuthenticatedRequest, res, next) => {
  try {
    const { prompt, history } = req.body;
    const response = await GemmaProviderService.chat(req.user!.id, prompt, history);
    res.json(response);
  } catch (err) {
    next(err);
  }
});

// 3. Explicit Confirmation Execution for Previews Generated by Gemma
const ConfirmActionSchema = z.object({
  actionType: z.enum(['TRANSACTION', 'CUSTOMER']),
  data: z.record(z.any()),
});

gemmaRouter.post('/confirm-action', validateBody(ConfirmActionSchema), async (req: AuthenticatedRequest, res, next) => {
  try {
    const { actionType, data } = req.body;

    if (actionType === 'CUSTOMER') {
      const customer = await CustomerService.createCustomer(req.user!.id, {
        name: data.name,
        phone: data.phone || undefined,
        notes: data.notes || undefined,
        openingBalancePaise: data.openingBalancePaise || 0,
      });

      res.status(201).json({
        success: true,
        message: `✓ Confirmed and registered customer ${customer.name}`,
        customer,
      });
      return;
    }

    if (actionType === 'TRANSACTION') {
      if (!data.customerId) {
        res.status(400).json({ error: 'Customer ID is required to record transaction' });
        return;
      }

      const transaction = await TransactionService.createTransaction(req.user!.id, {
        customerId: data.customerId,
        type: data.type,
        amount: Number(data.amount),
        description: data.description || 'Gemma AI confirmed entry',
        dueDate: data.dueDate,
        source: 'VOICE',
        paymentMode: data.type === 'PAYMENT' ? (data.paymentMode || 'CASH') : undefined,
      });

      res.status(201).json({
        success: true,
        message: `✓ Confirmed and posted ${transaction.type} transaction of ₹${data.amount}`,
        transaction,
      });
      return;
    }

    res.status(400).json({ error: 'Unsupported action type' });
  } catch (err) {
    next(err);
  }
});
